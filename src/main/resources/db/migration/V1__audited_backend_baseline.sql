-- The audited a6c1923 schema. Fresh databases run this before V2.
-- Existing nonempty databases require the reviewed baseline procedure in ops/DATABASE.md.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE charging_stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_name VARCHAR(150) NOT NULL,
    location VARCHAR(255) NOT NULL,
    total_slots INTEGER NOT NULL,
    avaialable_slots INTEGER NOT NULL,
    CONSTRAINT ck_station_capacity CHECK (
        total_slots > 0 AND avaialable_slots >= 0 AND avaialable_slots <= total_slots
    )
);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    station_id BIGINT NOT NULL,
    booking_status VARCHAR(255) NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    request_key VARCHAR(64),
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_booking_station FOREIGN KEY (station_id) REFERENCES charging_stations(id),
    CONSTRAINT uk_booking_request_key UNIQUE (request_key),
    CONSTRAINT ck_booking_validity CHECK (
        amount > 0 AND booking_status IN ('Confirmed', 'Cancelled')
    )
);

CREATE INDEX idx_booking_user ON booking(user_id);
CREATE INDEX idx_booking_station ON booking(station_id);
