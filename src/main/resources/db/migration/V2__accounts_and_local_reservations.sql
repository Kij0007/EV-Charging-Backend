ALTER TABLE users ADD COLUMN role VARCHAR(20) DEFAULT 'USER' NOT NULL;
ALTER TABLE users ADD COLUMN credential_version INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE users ADD CONSTRAINT ck_user_role CHECK (role IN ('USER', 'ADMIN'));
ALTER TABLE users ADD CONSTRAINT ck_credential_version CHECK (credential_version >= 0);

-- NULL password hashes intentionally leave imported users unable to sign in.
-- Registration and the explicit administrator bootstrap always store BCrypt hashes.
ALTER TABLE booking ADD COLUMN created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;
ALTER TABLE booking DROP CONSTRAINT ck_booking_validity;
ALTER TABLE booking ADD CONSTRAINT ck_booking_validity CHECK (
    amount >= 0 AND booking_status IN ('Confirmed', 'Cancelled', 'Completed')
);

CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    message VARCHAR(300) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    is_read BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_notification_user_created ON user_notifications(user_id, created_at);
